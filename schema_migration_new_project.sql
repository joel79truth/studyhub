  bio text,
  subjects text[],
  profile_pic text,
  quizzes_completed integer DEFAULT 0,
  accuracy_rate numeric DEFAULT 0,
  is_admin boolean DEFAULT false,
  total_questions integer DEFAULT 0,
  total_correct integer DEFAULT 0,
  daily_counts jsonb,
  badges text[],
  year text,
  program_id integer
